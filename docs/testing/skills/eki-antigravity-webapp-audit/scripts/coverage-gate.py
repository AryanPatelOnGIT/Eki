#!/usr/bin/env python3
"""Validate an Eki interaction-audit coverage ledger and generate summary JSON.

Run: python scripts/coverage-gate.py --coverage /path/to/coverage.csv \
      --inventory /path/to/control-inventory.json --output /path/to/coverage-summary.json

Exit codes: 0 = valid + no evidence errors/uncovered source candidates;
1 = incomplete (FAIL/BLOCKED/NOT_RUN/INCONCLUSIVE rows or missing source controls);
2 = malformed/unsupported evidence, invalid claims or missing files.
The exit code is a *coverage gate*, not a claim of software defect absence.
"""

import argparse
import collections
import csv
import datetime
import json
import pathlib
import re
import sys

VALID_STATUS = {"PASS", "FAIL", "BLOCKED", "NOT_RUN", "INCONCLUSIVE", "NOT_APPLICABLE"}
VALID_TIERS = {
    "STATIC",
    "UNIT",
    "SYNTHETIC_BROWSER",
    "EMULATOR_BROWSER",
    "LIVE_PROVIDER_BROWSER",
    "LIVE_CLOUD",
    "PHYSICAL_GNSS",
}
REQUIRED = {
    "control_id",
    "source_id",
    "page",
    "component",
    "source_path",
    "source_line",
    "role",
    "viewport",
    "environment",
    "evidence_tier",
    "entry_state",
    "control_name",
    "locator",
    "precondition",
    "action",
    "expected",
    "observed",
    "status",
    "executed",
    "oracle_passed",
    "evidence_path",
    "bug_id",
    "blocker_reason",
}
MATCH_FIELDS = (
    "control_id",
    "role",
    "viewport",
    "page",
    "precondition",
    "action",
    "expected",
    "observed",
)
RECORD_FIELDS = set(MATCH_FIELDS) | {
    "sha",
    "provider_tier",
    "http_status",
    "screenshot_path",
    "trace_path",
    "timestamp",
}


def validate_record(evidence, row):
    """Validate structure and ledger agreement, not the truth of observations."""
    try:
        record = json.loads(evidence.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        return [f"invalid action JSON: {error}"]
    if not isinstance(record, dict):
        return ["action evidence must be a JSON object"]
    missing = RECORD_FIELDS - record.keys()
    if missing:
        return ["action evidence missing fields: " + ", ".join(sorted(missing))]
    errors = []
    for field in MATCH_FIELDS:
        value = record[field]
        if (
            not isinstance(value, str)
            or not value.strip()
            or value.strip() != row[field].strip()
        ):
            errors.append(f"action evidence {field} must be nonempty and match ledger")
    if record["provider_tier"] != row["evidence_tier"].strip().upper():
        errors.append("action evidence provider_tier must match evidence_tier")
    if not isinstance(record["sha"], str) or not re.fullmatch(
        r"[0-9a-fA-F]{40}", record["sha"]
    ):
        errors.append("action evidence requires full commit sha")
    try:
        timestamp = datetime.datetime.fromisoformat(
            record["timestamp"].replace("Z", "+00:00")
        )
        if timestamp.utcoffset() is None:
            raise ValueError("timezone missing")
    except (AttributeError, TypeError, ValueError):
        errors.append("action evidence requires ISO timestamp with timezone")
    status = record["http_status"]
    if status is not None and (type(status) is not int or not 100 <= status <= 599):
        errors.append(
            "action evidence http_status must be null or an HTTP status integer"
        )
    for field in ("screenshot_path", "trace_path"):
        value = record[field]
        if not isinstance(value, str):
            errors.append(f"action evidence {field} must be a string")
        elif value.strip() and not (evidence.parent / value).is_file():
            errors.append(f"action evidence {field} file does not exist")
    return errors


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--coverage", required=True)
    p.add_argument("--inventory", help="Optional JSON generated by control-census.mjs")
    p.add_argument("--output", help="Summary JSON output; default next to coverage.csv")
    p.add_argument(
        "--strict",
        action="store_true",
        help="Require source-inventory reconciliation (recommended)",
    )
    a = p.parse_args()
    ledger = pathlib.Path(a.coverage).resolve()
    if not ledger.is_file():
        print(f"ERROR: coverage file missing: {ledger}", file=sys.stderr)
        return 2
    with ledger.open(encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        missing = REQUIRED - set(reader.fieldnames or [])
        if missing:
            print(
                "ERROR: missing headers: " + ", ".join(sorted(missing)), file=sys.stderr
            )
            return 2
        rows = list(reader)
    errors = []
    counts = collections.Counter()
    by_tier = collections.defaultdict(collections.Counter)
    seen_ids = set()
    covered_source = {}
    passed_runtime = 0
    for number, r in enumerate(rows, 2):
        if None in r or any(r.get(field) is None for field in REQUIRED):
            errors.append(f"line {number}: malformed/incomplete CSV row")
            continue
        row_start_errors = len(errors)
        status = r["status"].strip().upper()
        tier = r["evidence_tier"].strip().upper()
        cid = r["control_id"].strip()
        counts[status] += 1
        by_tier[tier][status] += 1
        if not cid:
            errors.append(f"line {number}: missing control_id")
        key = (cid, tier, r["role"], r["viewport"], r["environment"], r["entry_state"])
        if key in seen_ids:
            errors.append(f"line {number}: duplicate control/state identity {key}")
        seen_ids.add(key)
        if status not in VALID_STATUS:
            errors.append(f"line {number}: unrecognized status {status}")
        if tier not in VALID_TIERS:
            errors.append(f"line {number}: invalid evidence tier {tier}")
        if not r["expected"].strip():
            errors.append(f"line {number}: missing explicit expected result")
        if status == "NOT_APPLICABLE" and not r["blocker_reason"].strip():
            errors.append(f"line {number}: NOT_APPLICABLE requires reasoning")
        if (
            status in ("BLOCKED", "NOT_RUN", "INCONCLUSIVE")
            and not r["blocker_reason"].strip()
        ):
            errors.append(f"line {number}: {status} requires blocker reason")
        executed = r["executed"].strip().lower() == "true"
        oracle = r["oracle_passed"].strip().lower() == "true"
        if status in ("PASS", "FAIL"):
            if not executed:
                errors.append(f"line {number}: {status} requires executed=true")
            if status == "PASS" and not oracle:
                errors.append(f"line {number}: PASS requires oracle_passed=true")
            if status == "PASS" and tier in ("STATIC", "UNIT"):
                errors.append(
                    f"line {number}: UI interaction cannot PASS with {tier} tier; execute a browser interaction"
                )
            if not r["observed"].strip():
                errors.append(
                    f"line {number}: executed {status} requires observed result"
                )
            if status == "FAIL" and oracle:
                errors.append(f"line {number}: FAIL cannot have oracle_passed=true")
            ep = r["evidence_path"].strip()
            if not ep:
                errors.append(
                    f"line {number}: executed {status} requires evidence_path"
                )
            else:
                evidence = (
                    (ledger.parent / ep).resolve()
                    if not pathlib.Path(ep).is_absolute()
                    else pathlib.Path(ep)
                )
                if not evidence.is_file():
                    errors.append(f"line {number}: evidence file does not exist: {ep}")
                elif status == "PASS":
                    errors.extend(
                        f"line {number}: {error}"
                        for error in validate_record(evidence, r)
                    )
            if status == "PASS" and len(errors) == row_start_errors:
                passed_runtime += 1
        elif executed and status in ("NOT_RUN", "BLOCKED", "NOT_APPLICABLE"):
            errors.append(f"line {number}: {status} cannot have executed=true")
        source_id = r["source_id"].strip()
        if source_id:
            try:
                location = (
                    r["source_path"].strip().replace("\\", "/"),
                    int(r["source_line"]),
                )
                if not location[0] or location[1] < 1:
                    raise ValueError("missing location")
                covered_source.setdefault(source_id, set()).add(location)
            except ValueError:
                errors.append(
                    f"line {number}: source_id requires valid source_path/source_line"
                )
        elif r["source_path"].strip() or r["source_line"].strip():
            errors.append(
                f"line {number}: source location requires source_id from census"
            )
    inventory_count = None
    uncovered = []
    if a.inventory:
        f = pathlib.Path(a.inventory)
        if not f.is_file():
            errors.append(f"inventory missing: {f}")
        else:
            try:
                raw = json.loads(f.read_text(encoding="utf-8"))
                items = raw["candidates"] if isinstance(raw, dict) else raw
                expected = {}
                for item in items:
                    cid = item["id"]
                    location = (
                        item["source_path"].replace("\\", "/"),
                        int(item["source_line"]),
                    )
                    if (
                        not isinstance(cid, str)
                        or not cid.strip()
                        or cid in expected
                        or not location[0]
                        or location[1] < 1
                    ):
                        raise ValueError(
                            "invalid or duplicate candidate identity/location"
                        )
                    expected[cid] = location
                for cid, locations in covered_source.items():
                    if cid not in expected or locations != {expected[cid]}:
                        errors.append(
                            f"source_id {cid} does not match inventory location"
                        )
                uncovered = [
                    dict(id=cid, source_path=loc[0], source_line=loc[1])
                    for cid, loc in sorted(expected.items())
                    if cid not in covered_source
                ]
                inventory_count = len(items)
            except (ValueError, KeyError, TypeError, AttributeError, OSError) as ex:
                errors.append(f"invalid inventory: {ex}")
    else:
        if a.strict:
            errors.append("strict mode requires --inventory")
    if not rows:
        errors.append("coverage ledger has no rows")
    summary = {
        "rows": len(rows),
        "status_counts": dict(counts),
        "by_tier": {k: dict(v) for k, v in by_tier.items()},
        "runtime_browser_or_physical_pass_rows": passed_runtime,
        "source_candidate_count": inventory_count,
        "uncovered_source_count": len(uncovered),
        "uncovered_source_candidates": uncovered,
        "errors": errors,
    }
    out = (
        pathlib.Path(a.output) if a.output else ledger.parent / "coverage-summary.json"
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print(
        f"Rows={len(rows)}, counts={dict(counts)}, source_not_reconciled={len(uncovered)}, errors={len(errors)}"
    )
    print(f"Summary: {out}")
    for e in errors[:50]:
        print("ERROR " + e, file=sys.stderr)
    for item in uncovered[:20]:
        print(f"GAP {item['id']} {item['source_path']}:{item['source_line']}")
    if errors:
        return 2
    if uncovered and a.strict:
        return 1
    if any(counts[s] for s in ("FAIL", "BLOCKED", "NOT_RUN", "INCONCLUSIVE")):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
